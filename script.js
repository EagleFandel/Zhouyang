const finePointer = window.matchMedia("(pointer: fine)").matches;
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

const ambientVideos = [...document.querySelectorAll("[data-ambient-video]")];
const heroVideo = document.querySelector(".hero-media");
const heroVideoToggle = document.querySelector("[data-toggle-hero-video]");
const heroVideoIcon = heroVideoToggle.querySelector("[data-video-icon]");
const heroAudioOnceButton = document.querySelector("[data-play-hero-audio]");
let heroVideoUserPaused = reducedMotion;
let heroVideoVisible = true;
let heroAudioPlayed = false;
let heroAudioActive = false;

function updateHeroVideoControl(playing) {
  const label = playing ? "暂停背景视频" : "播放背景视频";
  heroVideoToggle.classList.toggle("is-playing", playing);
  heroVideoToggle.setAttribute("aria-label", label);
  heroVideoToggle.title = label;
  heroVideoIcon.textContent = playing ? "⏸" : "▶";
}

function updateHeroAudioControl() {
  const label = heroAudioActive
    ? heroVideo.paused
      ? "背景声音已暂停"
      : "背景声音播放中"
    : heroAudioPlayed
      ? "背景声音已播放"
      : "低音量播放一次背景声音";
  heroAudioOnceButton.disabled = heroAudioPlayed;
  heroAudioOnceButton.setAttribute("aria-label", label);
  heroAudioOnceButton.title = label;
  heroAudioOnceButton.querySelector("span").textContent = heroAudioActive ? "♫" : heroAudioPlayed ? "✓" : "🔈";
}

heroVideo.addEventListener("play", () => {
  updateHeroVideoControl(true);
  updateHeroAudioControl();
});
heroVideo.addEventListener("pause", () => {
  updateHeroVideoControl(false);
  updateHeroAudioControl();
});
heroVideoToggle.addEventListener("click", () => {
  if (heroVideo.paused) {
    heroVideoUserPaused = false;
    heroVideo.play().catch(() => updateHeroVideoControl(false));
  } else {
    heroVideoUserPaused = true;
    heroVideo.pause();
  }
});

heroAudioOnceButton.addEventListener("click", () => {
  if (heroAudioPlayed) return;
  heroAudioPlayed = true;
  heroAudioActive = true;
  heroVideoUserPaused = false;
  heroVideo.volume = 0.08;
  heroVideo.muted = false;
  heroVideo.currentTime = 0;
  updateHeroAudioControl();
  heroVideo.play().catch(() => {
    heroAudioPlayed = false;
    heroAudioActive = false;
    heroVideo.muted = true;
    updateHeroAudioControl();
  });
});

heroVideo.addEventListener("ended", () => {
  heroAudioActive = false;
  heroVideo.muted = true;
  heroVideo.currentTime = 0;
  updateHeroAudioControl();
  if (!heroVideoUserPaused && heroVideoVisible && !reducedMotion) {
    heroVideo.play().catch(() => updateHeroVideoControl(false));
  }
});

updateHeroVideoControl(false);
updateHeroAudioControl();
if (reducedMotion) {
  ambientVideos.forEach((video) => {
    video.pause();
    video.load();
  });
} else {
  const videoObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        const video = entry.target;
        if (video === heroVideo) heroVideoVisible = entry.isIntersecting;
        const canAutoplay = video !== heroVideo || !heroVideoUserPaused;
        if (entry.isIntersecting && canAutoplay) {
          video.play().catch(() => {});
        } else {
          video.pause();
        }
      });
    },
    { threshold: 0.24 },
  );
  ambientVideos.forEach((video) => videoObserver.observe(video));
}

if (finePointer && !reducedMotion) {
  document.querySelectorAll(".project-visual").forEach((visual) => {
    visual.addEventListener("pointermove", (event) => {
      const rect = visual.getBoundingClientRect();
      const x = (event.clientX - rect.left) / rect.width - 0.5;
      const y = (event.clientY - rect.top) / rect.height - 0.5;
      visual.style.setProperty("--tilt-x", `${y * -3}deg`);
      visual.style.setProperty("--tilt-y", `${x * 3}deg`);
    });
    visual.addEventListener("pointerleave", () => {
      visual.style.setProperty("--tilt-x", "0deg");
      visual.style.setProperty("--tilt-y", "0deg");
    });
  });
}

const localTime = document.querySelector("[data-local-time]");
function updateLocalTime() {
  const time = new Intl.DateTimeFormat("en-GB", {
    timeZone: "Europe/London",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  }).format(new Date());
  localTime.textContent = `LONDON ${time}`;
}
updateLocalTime();
setInterval(updateLocalTime, 60_000);
